def render_pdf(docx: Path) -> Path:
    subprocess.run([SOFFICE, "--headless", "--convert-to", "pdf", "--outdir", str(docx.parent), str(docx)], check=True, capture_output=True, timeout=300)
    return docx.with_suffix(".pdf")


def roman(n: int) -> str:
    return ["", "i", "ii", "iii", "iv", "v", "vi", "vii", "viii", "ix", "x"][n]


def norm(s: str) -> str:
    return re.sub(r"\s+", " ", s)


def compute_toc(pdf: Path) -> dict[int, str]:
    doc = pymupdf.open(str(pdf))
    texts = [re.sub(r"^(?:\d+|[ivx]+) ", "", norm(p.get_text()).strip()) for p in doc]
    start = next(i for i, t in enumerate(texts) if t.strip().startswith("CHAPTER 1 INTRODUCTION"))
    nums: dict[int, str] = {1: roman(2), 2: roman(3), 3: roman(4)}
    assert texts[1].startswith("BONAFIDE") and texts[2].startswith("ABSTRACT") and texts[3].startswith("TABLE OF CONTENTS"), [t[:30] for t in texts[:5]]

    def body_page(pat: str, from_idx: int = start) -> int:
        i = next(k for k in range(from_idx, len(texts)) if re.search(pat, texts[k]))
        return i - start + 1

    for row, pat in {4: r"^CHAPTER 1 INTRODUCTION", 5: r"1\.1 Background of the Selected Problem", 6: r"1\.2 Industry Relevance",
                     7: r"1\.3 Aim and Objective", 8: r"1\.4 Link to SDG", 9: r"^CHAPTER 2 LITERATURE", 10: r"^CHAPTER 3 METHODOLOGY",
                     11: r"^CHAPTER 4 FABRICATION", 12: r"^CHAPTER 5 RESULTS", 13: r"^CHAPTER 6 CONCLUSION", 14: r"^REFERENCES"}.items():
        nums[row] = str(body_page(pat))
    print("pages total:", len(doc), "body starts at pdf page", start + 1)
    return nums


