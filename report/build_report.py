def runs_of(p):
    return p.findall(W + "r")


def set_text(p, text, hl=False, sz=None, bold=None):
    rs = runs_of(p)
    first = rs[0]
    for r in rs[1:]:
        p.remove(r)
    for child in list(first):
        if child.tag in (W + "t", W + "br", W + "tab"):
            first.remove(child)
    t = etree.SubElement(first, W + "t")
    t.text = text
    t.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")
    rpr = first.find(W + "rPr")
    if rpr is None:
        rpr = etree.Element(W + "rPr")
        first.insert(0, rpr)
    if hl and rpr.find(W + "highlight") is None:
        h = etree.SubElement(rpr, W + "highlight")
        h.set(W + "val", "yellow")
    if sz:
        for tag in ("sz", "szCs"):
            e = rpr.find(W + tag)
            if e is None:
                e = etree.SubElement(rpr, W + tag)
            e.set(W + "val", str(sz))
    if bold is not None:
        for tag in ("b", "bCs"):
            e = rpr.find(W + tag)
            if bold and e is None:
                etree.SubElement(rpr, W + tag)
            if not bold and e is not None:
                rpr.remove(e)


def reorder_rpr(rpr):
    order = ["rStyle", "rFonts", "b", "bCs", "i", "iCs", "caps", "strike", "color", "spacing", "w", "kern", "position", "sz", "szCs", "highlight", "u", "effect", "bdr", "shd", "vertAlign", "lang"]
    kids = list(rpr)
    kids.sort(key=lambda e: order.index(etree.QName(e).localname) if etree.QName(e).localname in order else 99)
    for kd in kids:
        rpr.remove(kd)
    for kd in kids:
        rpr.append(kd)


def add_ppr(p, tag, attrs=None):
    ppr = p.find(W + "pPr")
    if ppr is None:
        ppr = etree.Element(W + "pPr")
        p.insert(0, ppr)
    el = etree.Element(W + tag)
    for k, v in (attrs or {}).items():
        el.set(W + k, v)
    return ppr, el


def page_break_before(p):
    ppr, el = add_ppr(p, "pageBreakBefore")
    idx = 0
    for i, c in enumerate(ppr):
        if etree.QName(c).localname in ("pStyle", "keepNext", "keepLines"):
            idx = i + 1
    ppr.insert(idx, el)


