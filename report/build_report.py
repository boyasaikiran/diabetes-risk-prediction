def resolve(text: str) -> str:
    text = _cite.sub(lambda m: ", ".join(f"[{NUM[k]}]" for k in m.group(1).split(",")), text)
    text = re.sub(r"\{([TFE]):([a-z0-9_]+)\}", lambda m: (labels[m.group(1) + ":" + m.group(2)] if m.group(1) != "E" else "Eq. (" + labels["E:" + m.group(2)] + ")"), text)
    text = text.replace("{BR0}", f"{C.M['brier_raw_vs_calibrated_train_oof'][0]:.4f}").replace("{BR1}", f"{C.M['brier_raw_vs_calibrated_train_oof'][1]:.4f}")
    text = text.replace("{THR}", f"{C.META['threshold']:.4f}")
    return text


